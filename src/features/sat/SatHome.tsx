import { useLiveQuery } from 'dexie-react-hooks';
import { Link } from 'react-router-dom';
import { db } from '../../db/db';
import { groupStats, masteryColor } from '../../lib/mastery';
import { SAT_DOMAINS, SAT_SKILLS, SAT_WEAKNESS_WEIGHT, type SatDomainId } from '../../generators/sat/skills';
import { Card, PageTitle } from '../../components/ui';

export const DESMOS_URL = 'https://www.desmos.com/calculator';

export function DesmosButton() {
  return (
    <a href={DESMOS_URL} target="_blank" rel="noopener noreferrer" className="inline-flex items-center gap-1 rounded-lg bg-emerald-600 px-3 py-1.5 text-sm font-medium text-white hover:bg-emerald-500">
      📈 Desmos
    </a>
  );
}

export function SatHome() {
  const data = useLiveQuery(async () => {
    const attempts = await db.attempts.where('subject').equals('sat').toArray();
    const qb = await db.qb.toArray();
    return { stats: groupStats(attempts, (a) => a.skill, Date.now()), attempts, qb };
  }, []);
  const dark = document.documentElement.classList.contains('dark');
  const tools = [
    { to: '/sat/practice', icon: '🎯', label: 'Adaptive practice', desc: 'Mixed questions, weighted to your weak skills' },
    { to: '/sat/spr', icon: '⌨️', label: 'SPR trainer', desc: 'Typed answers only + entry-rules drill' },
    { to: '/sat/mock', icon: '⏱️', label: 'Adaptive mock test', desc: '2 modules × 22 questions, 35 min each' },
    { to: '/sat/qb', icon: '📄', label: 'Question Bank tracker', desc: 'Log your College Board PDF questions' },
  ];
  return (
    <div className="space-y-4">
      <PageTitle sub="Questions are generated by code; answers are computed, never hand-written." action={<DesmosButton />}>
        SAT Math
      </PageTitle>
      <div className="grid gap-2 sm:grid-cols-2">
        {tools.map((t) => (
          <Link key={t.to} to={t.to} className="flex items-start gap-3 rounded-xl border border-slate-200 bg-white p-3 hover:border-blue-400 dark:border-slate-800 dark:bg-slate-900">
            <span className="text-xl" aria-hidden>
              {t.icon}
            </span>
            <span>
              <span className="block font-medium">{t.label}</span>
              <span className="block text-xs text-slate-500">{t.desc}</span>
            </span>
          </Link>
        ))}
      </div>
      {(Object.keys(SAT_DOMAINS) as SatDomainId[]).map((dom) => (
        <Card key={dom} title={SAT_DOMAINS[dom]}>
          <ul className="space-y-2">
            {SAT_SKILLS.filter((s) => s.domain === dom).map((s) => {
              const st = data?.stats.get(s.id);
              const qb = data?.qb.filter((q) => q.skill === s.id && q.result !== 'todo') ?? [];
              const qbRight = qb.filter((q) => q.result === 'right').length;
              const weak = (SAT_WEAKNESS_WEIGHT[s.id] ?? 1) >= 1.8;
              return (
                <li key={s.id}>
                  <Link to={`/sat/practice?skill=${s.id}`} className="flex items-center gap-2 rounded-lg p-1.5 hover:bg-slate-100 dark:hover:bg-slate-800">
                    <span className="h-4 w-4 shrink-0 rounded" style={{ backgroundColor: masteryColor(st?.mastery, dark) }} />
                    <span className="min-w-0 flex-1 text-sm">
                      {s.title}
                      {weak && <span className="ml-1 text-xs text-amber-600">· weak spot</span>}
                    </span>
                    <span className="shrink-0 text-right text-xs text-slate-500">
                      {st ? `${st.correct}/${st.attempts}` : '—'}
                      {qb.length > 0 && <span className="block">QB {qbRight}/{qb.length}</span>}
                    </span>
                  </Link>
                </li>
              );
            })}
          </ul>
        </Card>
      ))}
    </div>
  );
}
